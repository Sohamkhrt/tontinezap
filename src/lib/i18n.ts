export type TKey = keyof typeof dict;
export const translate = (lang: Lang, key: TKey): string => dict[key][lang];

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "fr", setLang: () => {} });
export function useT() {
  const { lang, setLang } = useContext(LangContext);
  return { lang, setLang, t: (k: TKey) => translate(lang, k) };
}

export const locale = (lang: Lang) => (lang === "fr" ? "fr-FR" : "en-US");
export const fmtNum = (n: number, lang: Lang) => new Intl.NumberFormat(locale(lang), { maximumFractionDigits: 0 }).format(n);
export const fmtXof = (n: number, lang: Lang) => `${fmtNum(Math.round(n), lang)} ${lang === "fr" ? "FCFA" : "CFA"}`;
export const fmtSats = (n: number, lang: Lang) => `${fmtNum(n, lang)} sats`;
export const fmtDate = (ts: number, lang: Lang) =>
  new Intl.DateTimeFormat(locale(lang), { day: "numeric", month: "short" }).format(new Date(ts));
export const fmtDateTime = (ts: number, lang: Lang) =>
  new Intl.DateTimeFormat(locale(lang), { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" }).format(new Date(ts));
